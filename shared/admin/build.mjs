import { build } from "esbuild";
import { writeFile } from "node:fs/promises";
for (const page of ["admin", "login", "setup"]) {
  const entry = page === "admin" ? "src/admin.js" : "src/auth.jsx";
  const result = await build({
    entryPoints: [entry],
    bundle: true,
    write: false,
    outdir: "build",
    minify: true,
    format: "iife",
    target: ["es2022"],
    define: {
      "process.env.NODE_ENV": '"production"',
      __SETUP__: String(page === "setup"),
    },
    legalComments: "inline",
  });
  const js = result.outputFiles
    .find((f) => f.path.endsWith(".js"))
    .text.replaceAll("</script", "<\\/script");
  const css =
    result.outputFiles.find((f) => f.path.endsWith(".css"))?.text || "";
  await writeFile(
    `${page}.html`,
    `<!doctype html>\n<!-- Generated by npm run build in shared/admin. Edit src/, not this file. -->\n<html lang="en" data-theme="kumo"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>Flop admin</title><style>${css}</style></head><body><div id="app"></div><script>${js}</script></body></html>\n`,
  );
}
